/**
 * @param {import('../analyze/compare.js').Comparison} comparison
 * @returns {string}
 */
function renderComparison(comparison) {
  const verdictCell = (/** @type {import('../analyze/compare.js').MetricChange} */ change) => {
    const percent =
      change.relative === null
        ? ''
        : ` (${change.relative > 0 ? '+' : ''}${Math.round(change.relative * 100)}%)`;
    const text = `${formatMetric(change.unit, change.before)} → ${formatMetric(change.unit, change.after)}${percent}`;
    if (change.verdict === 'regression') return `<td class="bad">▲ ${e(text)}</td>`;
    if (change.verdict === 'improvement') return `<td class="good">▼ ${e(text)}</td>`;
    return `<td>${e(text)}</td>`;
  };
  const changed = (
    /** @type {{ changes: import('../analyze/compare.js').MetricChange[] }} */ entry,
  ) => entry.changes.some((change) => change.verdict !== 'unchanged');
  const routeRows = comparison.routes
    .filter(changed)
    .map(
      (entry) =>
        `<tr><th scope="row">${e(entry.route)}</th><td>${entry.changes
          .filter((change) => change.verdict !== 'unchanged')
          .map((change) => `${e(change.label)}`)
          .join(', ')}</td>${['TTFB', 'LCP', 'Transferred', 'Requests']
          .map((label) => {
            const change = entry.changes.find((candidate) => candidate.label === label);
            return change ? verdictCell(change) : '<td>–</td>';
          })
          .join('')}</tr>`,
    )
    .join('');
  const endpointRows = comparison.endpoints
    .filter(changed)
    .map(
      (entry) =>
        `<tr><th scope="row"><code>${e(entry.endpoint)}</code></th>${['p50', 'p95', 'size']
          .map((label) => {
            const change = entry.changes.find((candidate) => candidate.label === label);
            return change ? verdictCell(change) : '<td>–</td>';
          })
          .join('')}</tr>`,
    )
    .join('');
  const list = (/** @type {string} */ title, /** @type {string[]} */ items) =>
    items.length > 0
      ? `<p><b>${e(title)}:</b> ${items.map((item) => `<code>${e(item)}</code>`).join(' ')}</p>`
      : '';

  return `<section id="baseline" aria-labelledby="baseline-h"><h2 id="baseline-h">Compared with baseline</h2>
<p class="lede">Baseline: <code>${e(comparison.baseline.path)}</code> (${e(comparison.baseline.target)}, ${e(formatDate(comparison.baseline.startedAt))}). A change counts when it exceeds 10% and a per-metric minimum. ▲ regression, ▼ improvement.</p>
<div class="tiles">${tile('Regressions', String(comparison.counts.regressions), 'route and endpoint metrics')}${tile('Improvements', String(comparison.counts.improvements), 'route and endpoint metrics')}</div>
${routeRows ? `<div class="table-wrap"><table><caption>Routes with significant changes (medians)</caption><thead><tr><th scope="col">Route</th><th scope="col">Changed</th><th scope="col">TTFB</th><th scope="col">LCP</th><th scope="col">Transferred</th><th scope="col">Requests</th></tr></thead><tbody>${routeRows}</tbody></table></div>` : '<p>No significant route changes.</p>'}
${endpointRows ? `<div class="table-wrap"><table><caption>Endpoints with significant changes</caption><thead><tr><th scope="col">Endpoint</th><th scope="col">p50</th><th scope="col">p95</th><th scope="col">Size</th></tr></thead><tbody>${endpointRows}</tbody></table></div>` : '<p>No significant endpoint changes.</p>'}
${list('New routes', comparison.newRoutes)}${list('Routes no longer measured', comparison.missingRoutes)}${list('New endpoints', comparison.newEndpoints)}${list('Endpoints no longer called', comparison.missingEndpoints)}
</section>`;
}

/**
 * @param {Array<{ run: number, cache: string, traceId: string }> | undefined} traces
 * @param {string | undefined} template
 * @returns {string}
 */
function renderTraces(traces, template) {
  if (!traces || traces.length === 0) return '';
  const items = traces
    .map((trace) => {
      const label = `${trace.cache} run ${trace.run}`;
      const link = traceUrl(template, trace.traceId);
      return link
        ? `<a href="${e(link)}" rel="noopener noreferrer">${e(label)}</a>`
        : `${e(label)} <code>${e(trace.traceId)}</code>`;
    })
    .join(' · ');
  return `<p class="files">Backend traces: ${items}</p>`;
}

/**
 * @param {Array<'page' | 'listed' | 'openapi' | 'repo'> | undefined} sources
 * @returns {string}
 */
function sourceLabel(sources) {
  if (!sources || sources.length === 0) return 'page';
  const names = { page: 'page', listed: 'listed', openapi: 'API spec', repo: 'repository' };
  const labels = sources.map((source) => names[source]);
  return sources.includes('page') ? labels.join(' + ') : `${labels.join(' + ')} only`;
}

