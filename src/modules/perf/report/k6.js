import { BRAND } from '../../../core/brand.js';

/**
 * Generates a k6 (https://k6.io) script from the measured route scenarios, for load tests larger
 * than one Node.js process can drive. The script mirrors LaunchScope's stress settings (closed
 * model → `ramping-vus`, open model → `ramping-arrival-rate`), replays each route's GET requests in
 * the same dependency levels, and turns the stress budgets into k6 thresholds.
 *
 * Nothing secret is written: header values are read from environment variables at run time,
 * and request bodies are never exported (allowlisted writes are listed in a comment instead).
 */

/**
 * @param {object} options
 * @param {import('../stress/scenario.js').Scenario[]} options.scenarios
 * @param {import('../settings.js').PerfSettings} options.settings
 * @param {Date} [options.now]
 * @returns {string}
 */
export function buildK6Script({ scenarios, settings, now = new Date() }) {
  const origin = settings.targetUrl.origin;
  /** @type {string[]} */
  const skippedWrites = [];
  const exported = scenarios
    .map((scenario) => ({
      name: scenario.slug,
      levels: scenario.levels
        .map((level) =>
          level.filter((request) => {
            if ((request.method ?? 'GET') === 'GET') return true;
            skippedWrites.push(request.label);
            return false;
          }),
        )
        .filter((level) => level.length > 0)
        .map((level) =>
          level.map((request) => ({ path: pathOf(request.url, origin), name: request.label })),
        ),
    }))
    .filter((scenario) => scenario.levels.length > 0);

  const headerEnv = Object.keys(settings.headers).map((name) => ({
    name,
    env: `LAUNCHSCOPE_HEADER_${name.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}`,
  }));
  const stress = settings.stress;
  const seconds = Math.max(1, Math.round(stress.stageDurationMs / 1000));
  const ramp = Math.max(1, Math.round(seconds / 10));
  const loads = stress.mode === 'open' ? stress.rates : stress.stages;
  const stages = loads.flatMap((target) => [
    { duration: `${ramp}s`, target },
    { duration: `${seconds}s`, target },
  ]);
  const executor =
    stress.mode === 'open'
      ? {
          executor: 'ramping-arrival-rate',
          startRate: 0,
          timeUnit: '1s',
          preAllocatedVUs: Math.max(10, Math.ceil(Math.max(...loads) * 2)),
          maxVUs: stress.maxInFlight,
          stages,
        }
      : { executor: 'ramping-vus', startVUs: 0, stages, gracefulRampDown: '5s' };
  const options = {
    scenarios: { routes: executor },
    thresholds: {
      http_req_failed: [`rate<${settings.budgets.stressErrorRate.warning}`],
      http_req_duration: [`p(95)<${settings.budgets.stressP95Ms.warning}`],
    },
  };

  const lines = [
    `// Generated by ${BRAND.name} ${BRAND.version} from ${settings.targetUrl.href} on ${now.toISOString()}.`,
    '// Run: k6 run k6-script.js   (override the target with: k6 run -e BASE_URL=https://staging.example.com k6-script.js)',
    ...(headerEnv.length > 0
      ? [
          '// Header values are read from environment variables, e.g.:',
          ...headerEnv.map((header) => `//   -e ${header.env}=...   (${header.name})`),
        ]
      : []),
    ...(skippedWrites.length > 0
      ? [
          '// Not exported (request bodies are never written to disk); add them by hand if needed:',
          ...[...new Set(skippedWrites)].map((label) => `//   ${label}`),
        ]
      : []),
    '',
    "import http from 'k6/http';",
    "import { check } from 'k6';",
    '',
    `export const options = ${JSON.stringify(options, null, 2)};`,
    '',
    `const BASE_URL = __ENV.BASE_URL || ${JSON.stringify(origin)};`,
    '',
    'const HEADERS = {',
    `  'user-agent': ${JSON.stringify(`${BRAND.command}-k6/${BRAND.version} (+${BRAND.repositoryUrl})`)},`,
    ...headerEnv.map((header) => `  ${JSON.stringify(header.name)}: __ENV.${header.env} || '',`),
    '};',
    '',
    '// Each route: the document, then its API calls in the order the browser made them (requests',
    '// in the same inner array ran in parallel).',
    `const SCENARIOS = ${JSON.stringify(exported, null, 2)};`,
    '',
    'export default function () {',
    '  const scenario = SCENARIOS[(__VU + __ITER) % SCENARIOS.length];',
    '  for (const level of scenario.levels) {',
    '    const responses = http.batch(',
    "      level.map((request) => ['GET', BASE_URL + request.path, null, { headers: HEADERS, tags: { name: request.name } }]),",
    '    );',
    '    for (const response of responses) {',
    "      check(response, { 'status < 400': (r) => r.status < 400 });",
    '    }',
    '  }',
    '}',
    '',
  ];
  return lines.join('\n');
}

/**
 * @param {string} url
 * @param {string} origin
 * @returns {string}
 */
function pathOf(url, origin) {
  const parsed = new URL(url);
  return parsed.origin === origin ? `${parsed.pathname}${parsed.search}` : parsed.href;
}
